/** A saved choice wins, then the browser's first supported language, then English. */
export function pickLocale(saved, languages = []) {
  if (LOCALES.includes(saved)) return saved
  const match = languages.map((tag) => tag.slice(0, 2).toLowerCase()).find((code) => LOCALES.includes(code))
  return match ?? 'en'
}

export function createTranslator(locale) {
  const table = MESSAGES[locale] ?? MESSAGES.en
  return (key, params = {}) => {
    const template = table[key] ?? MESSAGES.en[key] ?? key
    return template.replace(/\{(\w+)\}/g, (whole, name) => (name in params ? String(params[name]) : whole))
  }
}
